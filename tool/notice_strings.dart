// The texts of the push notifications are written in the ARB files (the `push*` keys) and generated for the backend,
// which writes the notice on the server, in the language of each device.
//
//   dart run tool/notice_strings.dart       rewrites backend/core/notice_strings.ts
//
// `flutter test` checks that the committed file is up to date.
import 'dart:convert';
import 'dart:io';

const outputPath = 'backend/core/notice_strings.ts';

/// The TypeScript module for the `push*` keys of the ARB files [arbs] (language code → parsed file).
String generateNoticeStrings(Map<String, Map<String, dynamic>> arbs) {
  final out = StringBuffer()
    ..writeln(
      '// Generated by `dart run tool/notice_strings.dart` from the `push*` keys of lib/l10n/*.arb: do not edit.',
    )
    ..writeln('// Placeholders are `{name}`: backend/core/notify.ts fills them.')
    ..writeln()
    ..writeln('export const noticeStrings: Record<string, Record<string, string>> = {');
  for (final MapEntry(key: lang, value: arb) in arbs.entries) {
    out.writeln('  $lang: {');
    for (final MapEntry(:key, :value) in arb.entries) {
      if (key.startsWith('push') && value is String) out.writeln('    $key: ${jsonEncode(value)},');
    }
    out.writeln('  },');
  }
  out.writeln('};');
  return out.toString();
}

Map<String, Map<String, dynamic>> readArbs() => {
  for (final lang in ['en', 'it'])
    lang: jsonDecode(File('lib/l10n/app_$lang.arb').readAsStringSync()) as Map<String, dynamic>,
};

void main() {
  File(outputPath).writeAsStringSync(generateNoticeStrings(readArbs()));
  stdout.writeln('Wrote $outputPath');
}
